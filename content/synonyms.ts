/**
 * 検索クエリ辞書（表記ゆれ / 言い換え）
 * ============================================================================
 *
 * 日本語SEOで「表記ゆれ対策」と呼ばれるものは、実は性質の違う2つが混ざっている。
 * 混ぜたまま対処すると、キーワードの羅列（＝スパム扱い）になって逆効果になる。
 *
 * ── 1. orthographic（表記ゆれ）──────────────────────────────
 *   ひらがな / カタカナ / 全角半角 / 長音符の有無 / 漢数字。
 *   検索エンジン側が正規化して吸収するので、**両方を本文に書く必要はない**。
 *   むしろ書くと不自然になるだけ。ここでやるべきは「サイト内で1つに統一する」こと。
 *   → 監査ではカバー率ではなく「ゆれずに統一されているか」を見る。
 *
 * ── 2. lexical（言い換え）──────────────────────────────────
 *   「AI開発スクール」と「プログラミングスクール」のように、
 *   文字ではなく**語彙そのものが違う**もの。これは正規化では繋がらない。
 *   検索意図としては同じ人が探しているのに、本文に一度も出てこなければ届かない。
 *   → 監査ではこちらのカバー率を見る。ただし埋め込むのはFAQの回答文など、
 *     文章として自然に成立する場所に限る。
 *
 * ── ラテン文字ブランドのカタカナ表記は lexical 扱い ───────────
 *   「TECHSTARS」と「テックスターズ」は、検索エンジンが自動で結び付けてくれない。
 *   日本語話者はカタカナで打つことが多いので、これは本文に出す必要がある。
 */

export interface QueryGroup {
  id: string;
  /** この軸が何を指すか */
  label: string;
  /** サイト内で使う正規表記。これ以外の表記ゆれは使わない */
  canonical: string;
  /** 検索エンジンが吸収する表記ゆれ。本文には書かない（統一チェック用） */
  orthographic: string[];
  /** 語彙が違う言い換え。検索意図が同じなら本文に一度は出す */
  lexical: string[];
}

